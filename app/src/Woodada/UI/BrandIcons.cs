internal sealed record BrandIcon(Geometry Geometry, double ViewBox)
{
    /// <summary>box 안에 꽉 차게(가로세로 비율 유지) 한 가지 색으로 그린다.</summary>
    public void Draw(DrawingContext ctx, Rect box, Color color)
    {
        double scale = Math.Min(box.Width, box.Height) / ViewBox;
        var matrix = Matrix.CreateScale(scale, scale) * Matrix.CreateTranslation(box.X, box.Y);
        using (ctx.PushTransform(matrix)) ctx.DrawGeometry(GameArt.Brush(color), null, Geometry);
    }
}

